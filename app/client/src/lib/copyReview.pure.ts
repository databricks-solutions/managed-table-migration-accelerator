import { copyEntries, type CopyEntry } from './sectionCopy';

const FIELD_LABELS: Record<string, string> = {
  title: 'Title',
  subtitle: 'Subtitle',
  detail: 'Tooltip',
  technical: 'Technical detail',
  badge: 'Badge',
  description: 'Description',
  label: 'Button',
  helper: 'Helper',
  explanation: 'Explanation',
  confirm: 'Confirm button',
  running: 'While running',
  toggle: 'Collapsed prompt',
  body: 'Body',
};

function escapeCell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

/** The copy review sheet (app/docs/copy-review.md), rendered from sectionCopy.ts. Pure. */
export function renderCopyReview(entries: CopyEntry[] = copyEntries()): string {
  const lines: string[] = [
    '# Copy review sheet',
    '',
    '<!-- Generated by `npm run copy:export` from client/src/lib/sectionCopy.ts. Do not edit by hand. -->',
    '',
    'Every page, section, button, and dialog heading in the app. Edit the wording in',
    '`app/client/src/lib/sectionCopy.ts`, then run `npm run copy:export` to refresh this sheet.',
    '`{name}` marks a value filled in at run time. "Technical detail" is shown only in a tooltip.',
    '',
  ];
  let group = '';
  let key = '';
  for (const e of entries) {
    if (e.group !== group) {
      group = e.group;
      key = '';
      lines.push(`## ${group}`, '');
    }
    if (e.key !== key) {
      if (key) lines.push('');
      key = e.key;
      lines.push(`### \`${key}\``, '', '| Field | Text |', '| --- | --- |');
    }
    lines.push(`| ${FIELD_LABELS[e.field] ?? e.field} | ${escapeCell(e.text)} |`);
  }
  lines.push('');
  return lines.join('\n');
}
